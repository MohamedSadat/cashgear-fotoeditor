import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { root, pnpmArgs, pnpmCommand } from './lib.mjs';

const allowed = new Set([
  'MIT',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'BSD-3-Clause-Clear',
  '0BSD',
  'ISC',
  'Zlib',
  'MPL-2.0',
  'Unicode-3.0',
  'Unicode-DFS-2016',
  'BSL-1.0',
  'CC0-1.0',
  'Unlicense',
  'BlueOak-1.0.0',
  'Apache-2.0 WITH LLVM-exception',
]);
function approved(expression) {
  // Cargo's legacy slash separator denotes alternative licenses.
  const tokens =
    expression.replace(/\s*\/\s*/g, ' OR ').match(/\(|\)|AND|OR|WITH|[A-Za-z0-9.+-]+/g) ?? [];
  let index = 0;
  function atom() {
    if (tokens[index] === '(') {
      index++;
      const value = or();
      if (tokens[index++] !== ')') throw new Error('Invalid SPDX expression: ' + expression);
      return value;
    }
    let license = tokens[index++];
    if (tokens[index] === 'WITH') {
      index++;
      license += ' WITH ' + tokens[index++];
    }
    return allowed.has(license);
  }
  function and() {
    let value = atom();
    while (tokens[index] === 'AND') {
      index++;
      const next = atom();
      value = value && next;
    }
    return value;
  }
  function or() {
    let value = and();
    while (tokens[index] === 'OR') {
      index++;
      const next = and();
      value = value || next;
    }
    return value;
  }
  const result = or();
  return result && index === tokens.length;
}
const entries = new Map();
const js = JSON.parse(
  execFileSync(pnpmCommand(), pnpmArgs(['licenses', 'list', '--json']), {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 30_000_000,
  }),
);
for (const packages of Object.values(js)) {
  for (const pkg of packages)
    for (const version of pkg.versions) {
      entries.set('npm:' + pkg.name + '@' + version, {
        ecosystem: 'npm',
        name: pkg.name,
        version,
        license: pkg.license,
      });
    }
}
for (const target of ['x86_64-pc-windows-msvc', 'wasm32-unknown-unknown']) {
  const meta = JSON.parse(
    execFileSync(
      'cargo',
      ['metadata', '--locked', '--format-version', '1', '--filter-platform', target],
      { cwd: root, encoding: 'utf8', maxBuffer: 40_000_000 },
    ),
  );
  const packages = new Map(meta.packages.map((pkg) => [pkg.id, pkg]));
  const nodes = new Map(meta.resolve.nodes.map((node) => [node.id, node]));
  const roots = target.startsWith('wasm')
    ? meta.packages.filter((pkg) => pkg.name === 'fotoeditor-wasm').map((pkg) => pkg.id)
    : meta.workspace_members;
  const seen = new Set();
  function visit(id) {
    if (seen.has(id)) return;
    seen.add(id);
    const pkg = packages.get(id);
    if (pkg?.source)
      entries.set('cargo:' + pkg.name + '@' + pkg.version, {
        ecosystem: 'Cargo',
        name: pkg.name,
        version: pkg.version,
        license: pkg.license ?? 'UNKNOWN',
      });
    for (const dep of nodes.get(id)?.deps ?? []) visit(dep.pkg);
  }
  roots.forEach(visit);
}
const rows = [...entries.values()].sort((a, b) =>
  (a.ecosystem + a.name + a.version).localeCompare(b.ecosystem + b.name + b.version),
);
const rejected = rows.filter((row) => !approved(row.license));
if (rejected.length)
  throw new Error(
    'Unreviewed dependency licenses:\n' +
      rejected.map((row) => row.name + '@' + row.version + ': ' + row.license).join('\n'),
  );
const output = [
  '# Dependency licenses',
  '',
  'Generated by pnpm licenses:update from installed npm metadata and the locked Cargo',
  'graphs for Windows x64 and the WASM engine. Includes build/test tools and transitive',
  'dependencies reachable on those targets. Other native platforms are outside P0.',
  '',
  'Approved licenses: MIT, Apache-2.0, BSD variants, ISC, Zlib, and MPL-2.0.',
  'MPL-2.0 is explicitly approved file-level copyleft, not a permissive license.',
  'Lightning CSS (Vite tooling) and some Tauri dependencies use MPL-2.0.',
  '',
  'Additional permissive/public-domain licenses in transitive tooling are allowed:',
  'BlueOak-1.0.0, Unicode-3.0, Unicode-DFS-2016, BSL-1.0, CC0-1.0, Unlicense,',
  'and Apache-2.0 WITH LLVM-exception. License alternatives are evaluated as SPDX',
  'expressions; at least one complete alternative must use approved licenses.',
  '',
  'No GPL/AGPL-only or paid dependencies are approved. Preserve upstream copyright',
  'and license notices when distributing dependencies. Package metadata is the',
  'inventory source; review actual license text before changing the policy.',
  '',
  'The downloaded wasm-bindgen CLI uses MIT OR Apache-2.0. Binaryen uses Apache-2.0.',
  'Rust uses MIT OR Apache-2.0; Node.js and pnpm use MIT. Windows toolchains and',
  'WebView2 are platform prerequisites, not bundled application libraries.',
  '',
  '| Ecosystem | Package | Version | SPDX license |',
  '| --- | --- | --- | --- |',
  ...rows.map(
    (row) =>
      '| ' + row.ecosystem + ' | ' + row.name + ' | ' + row.version + ' | ' + row.license + ' |',
  ),
  '',
].join('\n');
const path = root + '/docs/LICENSES.md';
if (process.argv.includes('--check')) {
  if ((await readFile(path, 'utf8')) !== output)
    throw new Error('License inventory is stale. Run pnpm licenses:update.');
} else {
  await writeFile(path, output);
}
console.log('Approved license expressions for ' + rows.length + ' dependencies.');
